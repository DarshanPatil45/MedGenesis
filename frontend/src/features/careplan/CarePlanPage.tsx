import { Activity, CalendarClock, ClipboardList, ExternalLink, Printer, Salad, Stethoscope, Sunrise, UserRound } from 'lucide-react'
import { motion, useReducedMotion } from 'motion/react'
import { useEffect, useState } from 'react'
import { api } from '../../api/client'
import type { CarePlan } from '../../api/types'
import {
  Button,
  Card,
  CardLabel,
  Chip,
  ClinicalImage,
  CountUp,
  EmptyState,
  ErrorState,
  MEDIA,
  Skeleton,
  StageHeader,
  Stat,
  resultReveal,
  riskColor,
  useAvailableMedia,
} from '../../design-system'
import { PageContainer } from '../../layouts/AppShell'
import { usePatients } from '../../PatientContext'
import { SafetyGate } from '../safety/SafetyGate'

/**
 * Domains rendered are exactly the fields `CarePlanOut` returns. The API
 * has no sleep recommendation, so no sleep section is shown. Order
 * matches the ACTIVITY / NUTRITION / MONITOR section sequence.
 */
const DOMAINS = [
  { key: 'activity_target', label: 'Activity', icon: Activity, slot: 'activity' },
  { key: 'diet_focus', label: 'Nutrition', icon: Salad, slot: 'nutrition' },
  { key: 'monitoring_frequency', label: 'Monitor', icon: Stethoscope, slot: 'monitoring' },
] as const

/** Slots backing the domain strip — see design-system/visuals/media.ts. */
const DOMAIN_SLOTS = ['nutrition', 'activity', 'monitoring'] as const

export function CarePlanPage() {
  const { selected } = usePatients()
  const [plan, setPlan] = useState<CarePlan | null>(null)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const reduced = useReducedMotion()
  const { complete: domainArt } = useAvailableMedia(DOMAIN_SLOTS)

  useEffect(() => setPlan(null), [selected?.id])

  const generate = async () => {
    if (!selected) return
    setBusy(true)
    setError(null)
    try {
      setPlan(await api.generateCarePlan(selected.id))
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e))
    } finally {
      setBusy(false)
    }
  }

  if (!selected) {
    return (
      <PageContainer className="py-16">
        <EmptyState
          icon={UserRound}
          title="No patient selected"
          reason="A care plan is generated from one patient's recorded context."
          action={<Chip tone="teal">Choose a patient from the chip in the top bar</Chip>}
        />
      </PageContainer>
    )
  }

  return (
    <>
      <section className="border-b border-border-strong no-print">
        <PageContainer className="py-12 lg:py-14">
          <StageHeader
            eyebrow="Care Plan"
            eyebrowIcon={ClipboardList}
            title="Care Plan"
            subtitle="Lifestyle-oriented suggestions produced by a deterministic rules engine and grounded in cited public-health sources. Points to discuss with a clinician — not a prescription."
            actions={
              <>
                <Button variant="primary" onClick={generate} disabled={busy}>
                  {busy ? 'Generating…' : plan ? 'Regenerate plan' : 'Generate care plan'}
                </Button>
                {plan && (
                  <Button variant="secondary" onClick={() => window.print()}>
                    <Printer size={15} /> Print
                  </Button>
                )}
              </>
            }
            /* Moved up from the inline summary row that used to sit at the
               top of the plan body — same real fields, promoted to the hero
               strip that every other screen now uses. */
            metrics={
              plan ? (
                <>
                  <Stat
                    label="Risk tier"
                    emphasis="key"
                    value={
                      <span style={{ color: riskColor[(plan.risk_tier ?? '').toLowerCase()] }}>
                        {plan.risk_tier ?? 'Not scored'}
                      </span>
                    }
                  />
                  <Stat label="Follow-up" value={<CountUp value={plan.follow_up_weeks} suffix=" wks" />} />
                  <Stat
                    label="Generated by"
                    value={<span className="font-mono text-sm">{plan.generated_by}</span>}
                  />
                  <Stat
                    label="Sources cited"
                    value={<CountUp value={plan.sources.length} />}
                    hint="public-health references"
                  />
                </>
              ) : undefined
            }
          />
        </PageContainer>
      </section>

      <PageContainer className="py-10 lg:py-12">
        <ErrorState error={error} onRetry={generate} />

        {busy && !plan && (
          <div className="space-y-4" role="status" aria-label="Generating care plan">
            <Skeleton className="h-32" />
            <Skeleton className="h-48" />
          </div>
        )}

        {!busy && !plan && (
          <EmptyState
            icon={ClipboardList}
            title="No care plan generated yet"
            reason="Generate a plan from this patient's available Digital Twin context and the cited evidence base."
            action={<Button variant="primary" onClick={generate}>Generate care plan</Button>}
          />
        )}

        {plan && (
          <motion.div variants={resultReveal} initial={reduced ? false : 'hidden'} animate="visible">
            {/*
              Paper only. The hero strip above carries these same fields on
              screen, but that whole section is `no-print` — without this,
              printing the plan would silently drop risk tier, follow-up and
              provenance, which used to be visible before that summary lived
              in the hero.
            */}
            <p className="print-only mb-6 text-sm">
              Risk tier: <strong>{plan.risk_tier ?? 'Not scored'}</strong> · Follow up in ~
              {plan.follow_up_weeks} weeks · Generated by <code>{plan.generated_by}</code>
            </p>

            {/*
              No context band here by design. This page is the plan itself,
              and the safety layer blocks medication advice — so imagery of
              insulin pens, syringes or pills would advertise a capability
              the product deliberately refuses. Domain art only.
            */}

            {/* Today — every field here already exists elsewhere on this
                page (risk tier in the hero, notes below, follow-up in its
                own section); this is a glance-view composed from those
                same real fields, not a new recommendation. */}
            <section className="mb-12">
              <CardLabel>Today</CardLabel>
              <Card layer="data" pad="lg">
                <div className="flex flex-wrap items-center gap-3">
                  <Sunrise size={16} className="text-teal" aria-hidden="true" />
                  <span
                    className="text-sm font-semibold"
                    style={{ color: riskColor[(plan.risk_tier ?? '').toLowerCase()] }}
                  >
                    {plan.risk_tier ?? 'Not scored'} risk
                  </span>
                  <span className="text-sm text-ink-3">· follow up in ~{plan.follow_up_weeks} weeks</span>
                </div>
                {plan.notes.length > 0 ? (
                  <ul className="mt-4 space-y-2.5 border-t border-border-strong pt-4">
                    {plan.notes.map((n, i) => (
                      <li key={i} className="flex gap-3 text-sm leading-relaxed text-ink">
                        <span aria-hidden="true" className="mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full bg-teal/60" />
                        {n}
                      </li>
                    ))}
                  </ul>
                ) : (
                  <p className="mt-4 border-t border-border-strong pt-4 text-sm text-ink-3">
                    No profile-specific notes for this plan — see Activity, Nutrition and Monitor below.
                  </p>
                )}
              </Card>
            </section>

            {/* Domains — editorial, not equal cards */}
            <div className="mb-12 grid gap-px overflow-hidden rounded-[14px] border border-border-strong bg-border-strong lg:grid-cols-3">
              {DOMAINS.map((d) => (
                <section key={d.key} className="flex flex-col bg-surface">
                  {/* Only when every domain has a photo — one image beside
                      two empty frames reads as a broken layout. */}
                  {domainArt && (
                    <ClinicalImage
                      src={MEDIA[d.slot].src}
                      alt={MEDIA[d.slot].alt}
                      aspect="16 / 7"
                      tone="muted"
                      className="rounded-none border-0 no-print"
                    />
                  )}
                  <div className="p-6">
                    <span className="flex items-center gap-2 text-[0.62rem] font-bold tracking-[0.16em] text-teal uppercase">
                      <d.icon size={12} /> {d.label}
                    </span>
                    <p className="mt-3 text-sm leading-relaxed text-ink">{plan[d.key]}</p>
                  </div>
                </section>
              ))}
            </div>

            <section className="mb-12">
              <CardLabel>Narrative</CardLabel>
              <div className="max-w-3xl text-[0.95rem] leading-[1.75] whitespace-pre-wrap text-ink-2">
                {plan.narrative_text}
              </div>
            </section>

            <section className="mb-12">
              <CardLabel>Follow-up</CardLabel>
              <Card layer="data" pad="md" className="max-w-xl">
                <div className="flex items-center gap-3">
                  <CalendarClock size={16} className="shrink-0 text-teal" aria-hidden="true" />
                  <p className="text-sm text-ink">
                    Check back in <strong className="font-mono">~{plan.follow_up_weeks}</strong> weeks, or sooner if
                    symptoms change.
                  </p>
                </div>
                <p className="mt-2.5 border-t border-border-strong pt-2.5 text-xs leading-relaxed text-ink-3">
                  A point to discuss with a clinician, not an appointment scheduled on your behalf.
                </p>
              </Card>
            </section>

            {plan.sources.length > 0 && (
              <section className="mb-12">
                <CardLabel>Evidence grounding</CardLabel>
                <p className="mb-4 max-w-3xl text-xs text-ink-3">
                  Sources are returned for the plan as a whole; the API does not attribute them to individual
                  recommendations.
                </p>
                <ul className="grid gap-4 lg:grid-cols-2">
                  {plan.sources.map((s, i) => (
                    <li key={i}>
                      <Card layer="data" pad="md">
                        <p className="text-sm font-medium text-ink">{s.section}</p>
                        <p className="mt-0.5 text-xs text-ink-3">{s.publisher}</p>
                        <p className="mt-2.5 text-xs leading-relaxed text-ink-2">{s.text.slice(0, 220)}…</p>
                        {s.source_url && (
                          <a href={s.source_url} target="_blank" rel="noreferrer"
                            className="mt-3 inline-flex items-center gap-1 text-xs text-teal hover:underline">
                            Open source <ExternalLink size={10} />
                          </a>
                        )}
                        {s.license?.toLowerCase().includes('copyright') && s.attribution && (
                          <p className="mt-2 text-[0.66rem] leading-relaxed text-ink-3 italic">{s.attribution}</p>
                        )}
                      </Card>
                    </li>
                  ))}
                </ul>
              </section>
            )}

            <SafetyGate safety={plan.safety} />
          </motion.div>
        )}
      </PageContainer>
    </>
  )
}
