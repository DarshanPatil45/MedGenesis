import { Sparkles } from 'lucide-react'
import { useState } from 'react'
import { api } from '../api/client'
import type { ChatResponse, Safety } from '../api/types'
import { usePatients } from '../PatientContext'
import { ErrorNote, Sources } from '../components/common'
import { SafetyStatus } from '../components/clinical/SafetyStatus'
import { ScopeDisclaimer } from '../components/SafetyBanner'

interface Turn {
  role: 'user' | 'agent'
  content: string
  safety?: Safety
  response?: ChatResponse
}

const SUGGESTIONS = [
  'How much exercise should I do each week?',
  'What should I eat to help manage blood sugar?',
  'How does losing weight affect diabetes risk?',
  'Why is sleep relevant to blood sugar?',
]

export function ChatPage() {
  const { selected } = usePatients()
  const [turns, setTurns] = useState<Turn[]>([])
  const [input, setInput] = useState('')
  const [sessionId, setSessionId] = useState<number | null>(null)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const send = async (text: string) => {
    if (!selected || !text.trim()) return
    setTurns((t) => [...t, { role: 'user', content: text }])
    setInput('')
    setBusy(true)
    setError(null)
    try {
      const resp = await api.chat(selected.id, text, sessionId)
      setSessionId(resp.session_id)
      setTurns((t) => [
        ...t,
        { role: 'agent', content: resp.reply_text, safety: resp.safety, response: resp },
      ])
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e))
    } finally {
      setBusy(false)
    }
  }

  if (!selected) return <p className="muted">Select a patient on the Intake page first.</p>

  const last = [...turns].reverse().find((t) => t.role === 'agent')

  return (
    <>
      <div className="section-block">
        <span className="eyebrow">
          <Sparkles /> Grounded conversational assistant
        </span>
        <h1 className="section-title">Chat</h1>
        <p className="section-lead">
          Restricted to lifestyle and education topics, grounded in cited sources. Every reply
          passes through the safety gate before it is shown.
        </p>
      </div>
      <ScopeDisclaimer />
      <ErrorNote error={error} />

      <div className="card" style={{ padding: 0 }}>
        <div className="chat-log" style={{ padding: 'var(--space-5)' }}>
          {turns.length === 0 && (
            <p className="muted">Ask a question, or try one of the suggestions below.</p>
          )}
          {turns.map((t, i) => (
            <div key={i} style={{ alignSelf: t.role === 'user' ? 'flex-end' : 'flex-start', maxWidth: '82%' }}>
              <span className="micro-label" style={{ marginBottom: 2, textAlign: t.role === 'user' ? 'right' : 'left' }}>
                {t.role === 'user' ? 'You' : 'MedGenesis'}
              </span>
              <div className={`msg ${t.role}`} style={{ maxWidth: '100%' }}>
                {t.content}
              </div>
              {t.role === 'agent' && t.response && t.response.sources.length > 0 && (
                <div style={{ marginTop: 4 }}>
                  {t.response.sources.map((_, si) => (
                    <span key={si} className="evidence-chip">
                      E{si + 1}
                    </span>
                  ))}
                </div>
              )}
            </div>
          ))}
          {busy && <div className="msg agent muted">Thinking…</div>}
        </div>

        <div style={{ borderTop: '1px solid var(--border)', padding: 'var(--space-4) var(--space-5)' }}>
          <div className="row">
            <input
              style={{ flex: 1, minWidth: 240 }}
              value={input}
              placeholder="Ask about diet, activity, monitoring…"
              onChange={(e) => setInput(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter' && !busy) void send(input)
              }}
            />
            <button onClick={() => void send(input)} disabled={busy || !input.trim()}>
              Send
            </button>
          </div>

          <div className="chip-row" style={{ marginTop: '0.75rem' }}>
            {SUGGESTIONS.map((s) => (
              <button key={s} type="button" className="chip" disabled={busy} onClick={() => void send(s)}>
                {s}
              </button>
            ))}
          </div>
        </div>
      </div>

      {last?.safety && (
        <div style={{ marginTop: 'var(--space-6)' }}>
          <SafetyStatus safety={last.safety} />
          {last.response && (
            <div className="section-block">
              <p className="muted" style={{ marginTop: 0 }}>
                Reply generated by <code>{last.response.generated_by}</code> · tools:{' '}
                {last.response.tools_used.join(', ') || 'none'}
              </p>
              <Sources sources={last.response.sources} />
            </div>
          )}
        </div>
      )}
    </>
  )
}
