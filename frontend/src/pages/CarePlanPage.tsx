import { useState } from 'react'
import { api } from '../api/client'
import type { CarePlan } from '../api/types'
import { usePatients } from '../PatientContext'
import { AgentTrace, Card, ErrorNote, RiskBadge, Sources } from '../components/common'
import { SafetyBanner, ScopeDisclaimer } from '../components/SafetyBanner'

export function CarePlanPage() {
  const { selected } = usePatients()
  const [plan, setPlan] = useState<CarePlan | null>(null)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const generate = async () => {
    if (!selected) return
    setBusy(true)
    setError(null)
    try {
      setPlan(await api.generateCarePlan(selected.id))
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e))
    } finally {
      setBusy(false)
    }
  }

  if (!selected) return <p className="muted">Select a patient on the Intake page first.</p>

  return (
    <>
      <h1>Care Plan</h1>
      <p className="muted">
        Lifestyle-only plan from a deterministic rules engine, grounded in cited public-health
        sources. The optional LLM rephrases the plan but never chooses its content.
      </p>
      <ScopeDisclaimer />
      <ErrorNote error={error} />

      <Card>
        <button onClick={generate} disabled={busy}>
          {busy ? 'Generating…' : 'Generate care plan'}
        </button>
      </Card>

      {plan && (
        <>
          <SafetyBanner safety={plan.safety} />

          <Card title="Plan">
            <div className="row" style={{ marginBottom: '0.8rem' }}>
              <span className="muted">Risk tier:</span> <RiskBadge tier={plan.risk_tier} />
              <span className="muted">· generated by</span> <code>{plan.generated_by}</code>
            </div>
            <dl className="kv">
              <dt>Diet focus</dt>
              <dd>{plan.diet_focus}</dd>
              <dt>Activity target</dt>
              <dd>{plan.activity_target}</dd>
              <dt>Monitoring</dt>
              <dd>{plan.monitoring_frequency}</dd>
              <dt>Follow-up</dt>
              <dd>in about {plan.follow_up_weeks} weeks</dd>
            </dl>
          </Card>

          {plan.notes.length > 0 && (
            <Card title="Profile-specific notes">
              <ul style={{ fontSize: '0.88rem' }}>
                {plan.notes.map((n, i) => (
                  <li key={i}>{n}</li>
                ))}
              </ul>
            </Card>
          )}

          <Card title="Narrative">
            <div style={{ whiteSpace: 'pre-wrap', fontSize: '0.9rem' }}>{plan.narrative_text}</div>
          </Card>

          <Card>
            <Sources sources={plan.sources} />
          </Card>

          <Card title="Agent trace">
            <AgentTrace trace={plan.trace} />
          </Card>
        </>
      )}
    </>
  )
}
