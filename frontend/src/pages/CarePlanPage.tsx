import { ArrowRight, ClipboardList, Database, Library, Sparkles } from 'lucide-react'
import { useState } from 'react'
import { api } from '../api/client'
import type { CarePlan } from '../api/types'
import { usePatients } from '../PatientContext'
import { AgentTrace, ErrorNote, RiskBadge, Sources } from '../components/common'
import { SafetyStatus } from '../components/clinical/SafetyStatus'
import { ScopeDisclaimer } from '../components/SafetyBanner'

const INPUTS_USED = [
  { icon: Database, label: 'Digital Twin', detail: "This patient's latest recorded measurements and history." },
  { icon: Library, label: 'Evidence', detail: 'Cited public-health sources grounding each recommendation.' },
  { icon: ClipboardList, label: 'Rules engine', detail: 'Deterministic logic decides content — the optional LLM only rephrases it.' },
]

export function CarePlanPage() {
  const { selected } = usePatients()
  const [plan, setPlan] = useState<CarePlan | null>(null)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const generate = async () => {
    if (!selected) return
    setBusy(true)
    setError(null)
    try {
      setPlan(await api.generateCarePlan(selected.id))
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e))
    } finally {
      setBusy(false)
    }
  }

  if (!selected) return <p className="muted">Select a patient on the Intake page first.</p>

  return (
    <>
      <div className="section-block">
        <span className="eyebrow">
          <Sparkles /> Rules engine, LLM-phrased
        </span>
        <h1 className="section-title">Care Plan</h1>
        <p className="section-lead">
          Lifestyle-oriented planning grounded in public-health evidence — not a substitute for
          clinical judgment.
        </p>
      </div>
      <ScopeDisclaimer />
      <ErrorNote error={error} />

      {!plan && (
        <div className="card" style={{ textAlign: 'center', padding: 'var(--space-8) var(--space-6)' }}>
          <span className="icon-badge" aria-hidden="true" style={{ margin: '0 auto var(--space-3)' }}>
            <ClipboardList size={18} />
          </span>
          <h2 style={{ marginBottom: 'var(--space-2)' }}>Care Plan</h2>
          <p className="muted" style={{ maxWidth: '42ch', margin: '0 auto var(--space-5)' }}>
            Generate a lifestyle-oriented plan from this patient's available Digital Twin context
            and cited evidence.
          </p>
          <button onClick={generate} disabled={busy}>
            {busy ? 'Generating…' : 'Generate care plan'}
            <ArrowRight size={15} style={{ marginLeft: 6, verticalAlign: -2 }} aria-hidden="true" />
          </button>
        </div>
      )}

      <div className="section-block" style={{ marginTop: 'var(--space-6)' }}>
        <span className="micro-label">Inputs used</span>
        <div className="metric-cluster">
          {INPUTS_USED.map((input) => (
            <div key={input.label} className="metric-cluster-item">
              <span className="metric-cluster-label" style={{ display: 'flex', alignItems: 'center', gap: 4 }}>
                <input.icon size={11} /> {input.label}
              </span>
              <span className="muted" style={{ fontSize: '0.8rem' }}>
                {input.detail}
              </span>
            </div>
          ))}
        </div>
      </div>

      {plan && (
        <>
          <SafetyStatus safety={plan.safety} />

          <div style={{ marginBottom: 'var(--space-5)' }}>
            <button className="secondary" onClick={generate} disabled={busy}>
              {busy ? 'Regenerating…' : 'Regenerate plan'}
            </button>
          </div>

          <div className="section-block">
            <span className="micro-label">Plan</span>
            <div className="row" style={{ marginBottom: '0.75rem' }}>
              <span className="muted">Risk tier:</span> <RiskBadge tier={plan.risk_tier} />
              <span className="muted">· generated by</span> <code>{plan.generated_by}</code>
            </div>
            <dl className="kv">
              <dt>Diet focus</dt>
              <dd>{plan.diet_focus}</dd>
              <dt>Activity target</dt>
              <dd>{plan.activity_target}</dd>
              <dt>Monitoring</dt>
              <dd>{plan.monitoring_frequency}</dd>
              <dt>Follow-up</dt>
              <dd>in about {plan.follow_up_weeks} weeks</dd>
            </dl>
          </div>

          {plan.notes.length > 0 && (
            <div className="section-block">
              <span className="micro-label">Profile-specific notes</span>
              <ul style={{ fontSize: '0.88rem' }}>
                {plan.notes.map((n, i) => (
                  <li key={i}>{n}</li>
                ))}
              </ul>
            </div>
          )}

          <div className="section-block">
            <span className="micro-label">Narrative</span>
            <div style={{ whiteSpace: 'pre-wrap', fontSize: '0.9rem' }}>{plan.narrative_text}</div>
          </div>

          <div className="section-block">
            <Sources sources={plan.sources} />
          </div>

          <details className="card">
            <summary className="row" style={{ gap: '0.5rem' }}>
              Agent trace
            </summary>
            <div className="details-body">
              <AgentTrace trace={plan.trace} />
            </div>
          </details>
        </>
      )}
    </>
  )
}
